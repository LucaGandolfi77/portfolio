#!/usr/bin/env python3
"""
Generate the GBA ROM header as an assembler include file (src/header_inc.s).

The header occupies ROM offset 0x000..0x0BF (the entry branch + Nintendo logo +
game info + checksum). The code itself starts at 0x0C0 (see crt0.s).
"""
import os

# --- Nintendo logo, 156 bytes (identical in every GBA ROM, incl. all homebrew).
# Extracted from a retail GBA cart dump (same public blob documented in GBATEK).
LOGO = bytes([
    0x24, 0xFF, 0xAE, 0x51, 0x69, 0x9A, 0xA2, 0x21, 0x3D, 0x84, 0x82, 0x0A,
    0x84, 0xE4, 0x09, 0xAD, 0x11, 0x24, 0x8B, 0x98, 0xC0, 0x81, 0x7F, 0x21,
    0xA3, 0x52, 0xBE, 0x19, 0x93, 0x09, 0xCE, 0x20, 0x10, 0x46, 0x4A, 0x4A,
    0xF8, 0x27, 0x31, 0xEC, 0x58, 0xC7, 0xE8, 0x33, 0x82, 0xE3, 0xCE, 0xBF,
    0x85, 0xF4, 0xDF, 0x94, 0xCE, 0x4B, 0x09, 0xC1, 0x94, 0x56, 0x8A, 0xC0,
    0x13, 0x72, 0xA7, 0xFC, 0x9F, 0x84, 0x4D, 0x73, 0xA3, 0xCA, 0x9A, 0x61,
    0x58, 0x97, 0xA3, 0x27, 0xFC, 0x03, 0x98, 0x76, 0x23, 0x1D, 0xC7, 0x61,
    0x03, 0x04, 0xAE, 0x56, 0xBF, 0x38, 0x84, 0x00, 0x40, 0xA7, 0x0E, 0xFD,
    0xFF, 0x52, 0xFE, 0x03, 0x6F, 0x95, 0x30, 0xF1, 0x97, 0xFB, 0xC0, 0x85,
    0x60, 0xD6, 0x80, 0x25, 0xA9, 0x63, 0xBE, 0x03, 0x01, 0x4E, 0x38, 0xE2,
    0xF9, 0xA2, 0x34, 0xFF, 0xBB, 0x3E, 0x03, 0x44, 0x78, 0x00, 0x90, 0xCB,
    0x88, 0x11, 0x3A, 0x94, 0x65, 0xC0, 0x7C, 0x63, 0x87, 0xF0, 0x3C, 0xAF,
    0xD6, 0x25, 0xE4, 0x8B, 0x38, 0x0A, 0xAC, 0x72, 0x21, 0xD4, 0xF8, 0x07,
])

TITLE = b"POCKETWALKER"      # 12 chars, uppercase
GAME_CODE = b"PWKR"          # 4 chars
MAKER_CODE = b"LU"           # 2 chars


def build_header() -> bytearray:
    h = bytearray(0xC0)
    # 0x000: ARM branch over the header to the code at 0x0C0.
    # B <label>: offset = (0x0C0 - (0x000 + 8)) / 4 = 46 -> 0xEA00002E
    h[0:4] = (0xEA000000 | 46).to_bytes(4, "little")
    # 0x004..0x09F: Nintendo logo
    h[0x04:0xA0] = LOGO
    # 0x0A0..0x0AB: game title
    h[0xA0:0xAC] = TITLE.ljust(12, b"\x00")[:12]
    # 0x0AC..0x0AF: game code, 0x0B0..0x0B1: maker code
    h[0xAC:0xB0] = GAME_CODE.ljust(4, b"\x00")[:4]
    h[0xB0:0xB2] = MAKER_CODE.ljust(2, b"\x00")[:2]
    h[0xB2] = 0x96             # fixed value for GBA
    h[0xB3] = 0x00             # main unit code (GBA)
    h[0xB4] = 0x00             # device type
    h[0xB5:0xB8] = b"\x00\x00\x00"
    h[0xB8] = 0x00             # software version
    # 0x0B9: complement check
    h[0xB9] = (0x100 - (sum(h[0xA0:0xBC]) & 0xFF)) & 0xFF
    # 0x0BA..0x0BF: reserved + RAM entry
    h[0xBA:0xC0] = b"\x00\x00\x00\x00\x00\x00"
    return h


def emit_s(out, h: bytearray) -> None:
    """Emit the header WITHOUT the 4-byte entry branch (crt0.s writes it)."""
    out.write("/* Generated by tools/gen_header.py - do not edit. */\n")
    body = h[0x04:0xC0]
    items = ["0x%02X" % b for b in body]
    for i in range(0, len(items), 12):
        out.write("    .byte " + ", ".join(items[i:i + 12]) + "\n")


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(here, "..", "src", "header_inc.s")
    h = build_header()
    with open(out_path, "w") as f:
        emit_s(f, h)
    print("wrote", os.path.normpath(out_path))
    print("checksum: 0x%02X" % h[0xB9])


if __name__ == "__main__":
    main()
