const TAU = Math.PI * 2;

const E = (c, x, y, rx, ry = rx, rot = 0) => { c.beginPath(); c.ellipse(x, y, rx, ry, rot, 0, TAU); c.stroke(); };
const C = (c, x, y, r) => E(c, x, y, r, r);
const R = (c, x, y, w, h, r = 0) => { c.beginPath(); c.roundRect(x, y, w, h, r); c.stroke(); };
const L = (c, ...p) => { c.beginPath(); c.moveTo(p[0], p[1]); for (let i = 2; i < p.length; i += 2) c.lineTo(p[i], p[i + 1]); c.stroke(); };
const P = (c, pts, close = true) => {
  c.beginPath(); c.moveTo(pts[0][0], pts[0][1]);
  for (let i = 1; i < pts.length; i++) c.lineTo(pts[i][0], pts[i][1]);
  if (close) c.closePath();
  c.stroke();
};
const A = (c, x, y, r, a1 = 0, a2 = TAU) => { c.beginPath(); c.arc(x, y, r, a1, a2); c.stroke(); };
const Q = (c, x1, y1, cx, cy, x2, y2) => { c.beginPath(); c.moveTo(x1, y1); c.quadraticCurveTo(cx, cy, x2, y2); c.stroke(); };
const B = (c, x1, y1, c1x, c1y, c2x, c2y, x2, y2) => {
  c.beginPath(); c.moveTo(x1, y1); c.bezierCurveTo(c1x, c1y, c2x, c2y, x2, y2); c.stroke();
};
const S = (c, cx, cy, r1, r2, n, rot = -Math.PI / 2) => {
  const pts = [];
  for (let i = 0; i < n * 2; i++) {
    const a = rot + i * Math.PI / n;
    const r = i % 2 ? r2 : r1;
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  P(c, pts);
};
const H = (c, cx, cy, s) => {
  c.beginPath();
  c.moveTo(cx, cy + s * 0.85);
  c.bezierCurveTo(cx - s * 1.3, cy - s * 0.1, cx - s * 0.5, cy - s * 1.1, cx, cy - s * 0.45);
  c.bezierCurveTo(cx + s * 0.5, cy - s * 1.1, cx + s * 1.3, cy - s * 0.1, cx, cy + s * 0.85);
  c.closePath(); c.stroke();
};

