const listeners = new Set();
function stored() {
  try {
    const v = localStorage.getItem('site_lang') || localStorage.getItem('lang');
    if (v === 'it' || v === 'en') return v;
  } catch (e) { /* ignore */ }
  try { return (navigator.language || 'en').toLowerCase().startsWith('it') ? 'it' : 'en'; }
  catch (e) { return 'en'; }
}
let current = stored();
export function getLang() { return current; }
export function setLang(l) {
  if (l !== 'it' && l !== 'en') return;
  current = l;
  try { localStorage.setItem('site_lang', l); localStorage.setItem('lang', l); } catch (e) { /* ignore */ }
  listeners.forEach(fn => { try { fn(l); } catch (e) { /* ignore */ } });
}
export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
export function t(key, vars) {
  let v = (DICT[current] && DICT[current][key]) || DICT.en[key] || key;
  if (vars) Object.keys(vars).forEach(k => { v = v.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k])); });
  return v;
}
