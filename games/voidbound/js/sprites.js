  function generate_sprite(key, config, body_type, frames, scale) {
    const cached = cache[key];
    if (cached) return cached;

    const body = BODY_TEMPLATES[body_type];
    const palette = config.palette;
    const result = {};

    for (const frame_name of frames) {
      const body_data = body[frame_name] || body.idle;
      const h = body_data.length;
      const w = body_data[0].length;
      const total_w = w + 8;
      const total_h = h + 2;

      const c = create_canvas(total_w * scale, total_h * scale);
      const ctx = c.getContext('2d');
      draw_pixels(ctx, 0, 0, body_data, palette, scale);

      if (config.weapon && WEAPON_FRAMES[config.weapon] && WEAPON_FRAMES[config.weapon][frame_name]) {
        draw_pixels(ctx, 0, 0, WEAPON_FRAMES[config.weapon][frame_name], palette, scale);
      }

      result[frame_name] = c;
    }

    cache[key] = result;
    return result;
  }

  function generate_creep_sprite(type, config) {
    const key = 'creep_' + type;
    if (cache[key]) return cache[key];

    const shape = CREEP_SHAPES[config.shape];
    const palette = config.palette;
    const scale = Math.max(2, Math.round(config.size * 3));
    const result = {};

    for (const frame_name of ['idle', 'walk1']) {
      const data = shape;
      const c = create_canvas(data[0].length * scale, data.length * scale);
      const ctx = c.getContext('2d');
      const oy = frame_name === 'walk1' ? scale : 0;
      draw_pixels(ctx, 0, oy, data, palette, scale);
      result[frame_name] = c;
    }

    cache[key] = result;
    return result;
  }

