  function get_champion_sprites(roster_idx) {
    const r = VOIDBOUND.ROSTER[roster_idx];
    const config = CHAMPION_CONFIGS[r.id];
    if (!config) return null;
    return generate_sprite('champ_' + r.id, config, config.body, ['idle', 'walk1', 'walk2', 'attack'], 2);
  }

  function get_creep_sprites(type) {
    return generate_creep_sprite(type, CREEP_CONFIGS[type]);
  }

  function get_boss_sprites() {
    return generate_boss_sprite();
  }

  function generate_all() {
    for (let i = 0; i < VOIDBOUND.ROSTER.length; i++) {
      get_champion_sprites(i);
    }
    for (const type of Object.keys(CREEP_CONFIGS)) {
      get_creep_sprites(type);
    }
    get_boss_sprites();
  }

  function get_glow(color, radius) {
    const key = 'glow_' + color + '_' + radius;
    if (cache[key]) return cache[key];
    const c = create_canvas(radius * 4, radius * 4);
    const ctx = c.getContext('2d');
    const grad = ctx.createRadialGradient(radius * 2, radius * 2, 0, radius * 2, radius * 2, radius * 2);
    grad.addColorStop(0, color + '60');
    grad.addColorStop(0.5, color + '20');
    grad.addColorStop(1, color + '00');
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, radius * 4, radius * 4);
    cache[key] = c;
    return c;
  }

