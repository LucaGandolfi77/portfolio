export class I18n {
  constructor() {
    let lang = 'en';
    try { lang = (localStorage.getItem('pf.lang') || localStorage.getItem('site_lang') || 'en').slice(0, 2); }
    catch (e) { /* ignore */ }
    this.lang = lang === 'it' ? 'it' : 'en';
  }

  t(key, vars = {}) {
    let text = (this.lang === 'it' ? IT : EN)[key] || EN[key] || key;
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  }

  apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = this.t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
    document.documentElement.lang = this.lang;
  }

  setLang(lang) {
    this.lang = lang === 'it' ? 'it' : 'en';
    try {
      localStorage.setItem('pf.lang', this.lang);
      localStorage.setItem('site_lang', this.lang);
    } catch (e) { /* ignore */ }
    return this;
  }
}
